/** RSS 2.0 for the blog: feed readers, aggregators and AI crawlers pick up new posts from it. */
const writeBlogFeed = (siteConfig: SiteConfig) => {
  const blogDir = join(siteConfig.srcDir, 'blog')
  const field = (src: string, key: string) =>
    src
      .match(new RegExp(`^${key}:\\s*(.*)$`, 'm'))?.[1]
      ?.trim()
      .replace(/^(['"])(.*)\1$/, '$2')
  const items = readdirSync(blogDir)
    .filter((file) => file.endsWith('.md') && file !== 'index.md')
    .map((file) => {
      const src = readFileSync(join(blogDir, file), 'utf8')
      const front = src.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? ''
      return {
        slug: file.replace(/\.md$/, ''),
        title: field(front, 'title') ?? file,
        description: field(front, 'description') ?? '',
        date: toIsoDay(field(front, 'date')) ?? '1970-01-01',
        category: field(front, 'category'),
        cover: field(front, 'cover'),
        skip: /^(hidden|noindex):\s*true\s*$/m.test(front),
      }
    })
    .filter((post) => !post.skip)
    .sort((left, right) => right.date.localeCompare(left.date))

  const item = (post: (typeof items)[number]) => {
    const link = `${SITE_URL}/blog/${post.slug}`
    return [
      '    <item>',
      `      <title>${escapeXml(post.title)}</title>`,
      `      <link>${link}</link>`,
      `      <guid isPermaLink="true">${link}</guid>`,
      `      <pubDate>${new Date(`${post.date}T00:00:00Z`).toUTCString()}</pubDate>`,
      `      <description>${escapeXml(post.description)}</description>`,
      post.category ? `      <category>${escapeXml(post.category)}</category>` : '',
      post.cover
        ? `      <enclosure url="${SITE_URL}${post.cover}" type="image/${post.cover.endsWith('.png') ? 'png' : 'jpeg'}" length="0" />`
        : '',
      `      <dc:creator>${AUTHOR_NAME}</dc:creator>`,
      '    </item>',
    ]
      .filter(Boolean)
      .join('\n')
  }

  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/">',
    '  <channel>',
    `    <title>${SITE_NAME} blog</title>`,
    `    <link>${SITE_URL}/blog/</link>`,
    `    <atom:link href="${SITE_URL}/feed.xml" rel="self" type="application/rss+xml" />`,
    '    <description>Tutorials, framework guides and release notes for tanstack-fetch.</description>',
    '    <language>en-us</language>',
    `    <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>`,
    ...items.map(item),
    '  </channel>',
    '</rss>',
    '',
  ].join('\n')
  writeFileSync(join(siteConfig.outDir, 'feed.xml'), xml, 'utf8')
}

const buildJsonLd = (page: JsonLdPage) => {
  const { url: pageUrl, title, description } = page
  const sectionName = page.section && SECTION_NAMES[page.section]
  const crumbs = [
    { name: SITE_NAME, url: `${SITE_URL}/` },
    ...(sectionName && page.section !== 'docs'
      ? [{ name: sectionName, url: `${SITE_URL}/${page.section === 'blog' ? 'blog/' : 'docs'}` }]
      : []),
    ...(pageUrl === `${SITE_URL}/` ? [] : [{ name: title.replace(/\s+\|.*$/, ''), url: pageUrl }]),
  ]
  const article =
    page.kind === 'other'
      ? []
      : [
          {
            '@type': page.kind === 'blog' ? 'BlogPosting' : 'TechArticle',
            '@id': `${pageUrl}#article`,
            headline: title.replace(/\s+\|.*$/, '').slice(0, 110),
            description,
            image: page.image,
            url: pageUrl,
            mainEntityOfPage: { '@id': `${pageUrl}#webpage` },
            author: { '@id': `${SITE_URL}/#person` },
            publisher: { '@id': `${SITE_URL}/#person` },
            about: { '@id': `${SITE_URL}/#software` },
            ...(page.published ? { datePublished: page.published } : {}),
            ...(page.modified ? { dateModified: page.modified } : {}),
            ...(page.tags?.length ? { keywords: page.tags.join(', ') } : {}),
            ...(sectionName ? { articleSection: sectionName } : {}),
            isAccessibleForFree: true,
            inLanguage: 'en-US',
          },
        ]
  const graph: Record<string, unknown>[] = [
    {
      '@type': 'WebSite',
      '@id': `${SITE_URL}/#website`,
      url: `${SITE_URL}/`,
      name: SITE_NAME,
      description: DEFAULT_DESCRIPTION,
      publisher: { '@id': `${SITE_URL}/#person` },
      inLanguage: 'en-US',
    },
    {
      '@type': 'WebPage',
      '@id': `${pageUrl}#webpage`,
      url: pageUrl,
      name: title,
      description,
      isPartOf: { '@id': `${SITE_URL}/#website` },
      breadcrumb: { '@id': `${pageUrl}#breadcrumb` },
      primaryImageOfPage: { '@type': 'ImageObject', url: page.image },
      ...(page.modified ? { dateModified: page.modified } : {}),
      about: { '@id': `${SITE_URL}/#software` },
      author: { '@id': `${SITE_URL}/#person` },
      creator: { '@id': `${SITE_URL}/#person` },
      inLanguage: 'en-US',
    },
    {
      '@type': 'SoftwareApplication',
      '@id': `${SITE_URL}/#software`,
      name: SITE_NAME,
      applicationCategory: 'DeveloperApplication',
      operatingSystem: 'Any',
      description: DEFAULT_DESCRIPTION,
      url: `${SITE_URL}/`,
      downloadUrl: NPM_URL,
      softwareVersion: PACKAGE_VERSION,
      license: 'https://opensource.org/licenses/MIT',
      codeRepository: GITHUB_URL,
      programmingLanguage: ['TypeScript', 'JavaScript'],
      author: { '@id': `${SITE_URL}/#person` },
      creator: { '@id': `${SITE_URL}/#person` },
      offers: {
        '@type': 'Offer',
        price: '0',
        priceCurrency: 'USD',
      },
    },
    {
      '@type': 'Person',
      '@id': `${SITE_URL}/#person`,
      name: AUTHOR_NAME,
      url: AUTHOR_URL,
      email: AUTHOR_EMAIL,
      jobTitle: 'Software Engineer',
      sameAs: [GITHUB_PROFILE_URL, LINKEDIN_URL, NPM_URL, AUTHOR_URL],
    },
  ]

  graph.push(
    {
      '@type': 'BreadcrumbList',
      '@id': `${pageUrl}#breadcrumb`,
      itemListElement: crumbs.map((crumb, index) => ({
        '@type': 'ListItem',
        position: index + 1,
        name: crumb.name,
        item: crumb.url,
      })),
    },
    ...article,
  )

  return {
    '@context': 'https://schema.org',
    '@graph': graph,
  }
}

