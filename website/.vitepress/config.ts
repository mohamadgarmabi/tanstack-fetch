const toIsoDay = (value: unknown) => {
  const date = value instanceof Date ? value : new Date(String(value))
  return Number.isNaN(date.getTime()) ? undefined : date.toISOString().slice(0, 10)
}

/** Day of the last commit that touched a page (VitePress sets `lastUpdated` after transformPageData). */
const gitModifiedDay = (file: string) => {
  try {
    const out = execFileSync('git', ['log', '-1', '--format=%cI', '--', file], { encoding: 'utf8' })
    return toIsoDay(out.trim() || undefined)
  } catch {
    return undefined
  }
}

